import { describe, expect, test } from 'vitest'

import {
  CLAUDE_CHECKSUMS_SNAPSHOT,
  CLAUDE_CHECKSUMS_SNAPSHOT_DATE,
  CLAUDE_CHECKSUMS_URL,
  fetchClaudeChecksums,
  parseChecksumManifest,
} from '../lib/checksums'

const MAC_HASH =
  'a1d7ec9c231ea10f71562f3e1fd48dcc4cba415dfc045131e55bdb23d4d2b373'
const WIN_HASH =
  'bc39cbe4bc26a9235737535232f5fba84875bd5f438994505b8ab123a8ef7cb9'

function textResponse(body: string, ok = true): Response {
  return {
    ok,
    text: async () => body,
  } as unknown as Response
}

describe('parseChecksumManifest', () => {
  test('parses the sha256sum format with two spaces and a binary marker', () => {
    const entries = parseChecksumManifest(
      `${MAC_HASH}  Claude-mac-universal.dmg\n${WIN_HASH} *Claude-win-x64.msix\n`
    )

    expect(entries).toEqual([
      { fileName: 'Claude-mac-universal.dmg', sha256: MAC_HASH },
      { fileName: 'Claude-win-x64.msix', sha256: WIN_HASH },
    ])
  })

  test('parses the BSD format and lowercases an uppercase digest', () => {
    const entries = parseChecksumManifest(
      `SHA256 (Claude-win-arm64.msix) = ${WIN_HASH.toUpperCase()}`
    )

    expect(entries).toEqual([
      { fileName: 'Claude-win-arm64.msix', sha256: WIN_HASH },
    ])
  })

  test('ignores blank lines, comments, and lines without a valid digest', () => {
    const entries = parseChecksumManifest(
      [
        '',
        '# generated by the release pipeline',
        'not-a-hash  Claude-mac-universal.dmg',
        `${MAC_HASH}  Claude-mac-universal.dmg`,
        '   ',
      ].join('\n')
    )

    expect(entries).toEqual([
      { fileName: 'Claude-mac-universal.dmg', sha256: MAC_HASH },
    ])
  })

  test('returns nothing for an empty body', () => {
    expect(parseChecksumManifest('')).toEqual([])
  })
})

describe('fetchClaudeChecksums', () => {
  test('reports live entries read from the mirror', async () => {
    const snapshot = await fetchClaudeChecksums((() =>
      Promise.resolve(
        textResponse(`${MAC_HASH}  Claude-mac-universal.dmg\n`)
      )) as typeof fetch)

    expect(snapshot.live).toBe(true)
    expect(snapshot.snapshotDate).toBeNull()
    expect(snapshot.entries).toEqual([
      { fileName: 'Claude-mac-universal.dmg', sha256: MAC_HASH },
    ])
  })

  test('degrades to the dated snapshot when the browser cannot read the mirror', async () => {
    const snapshot = await fetchClaudeChecksums((() =>
      Promise.reject(new Error('blocked by CORS'))) as typeof fetch)

    expect(snapshot.live).toBe(false)
    expect(snapshot.snapshotDate).toBe(CLAUDE_CHECKSUMS_SNAPSHOT_DATE)
    expect(snapshot.entries).toBe(CLAUDE_CHECKSUMS_SNAPSHOT)
  })

  test('degrades to the snapshot when the mirror answers without usable digests', async () => {
    const snapshot = await fetchClaudeChecksums((() =>
      Promise.resolve(textResponse('<html>not found</html>'))) as typeof fetch)

    expect(snapshot.live).toBe(false)
    expect(snapshot.entries).toBe(CLAUDE_CHECKSUMS_SNAPSHOT)
  })

  test('reads the published checksums endpoint', async () => {
    let requested: string | null = null
    await fetchClaudeChecksums(((input: RequestInfo | URL) => {
      requested = String(input)
      return Promise.resolve(textResponse(`${MAC_HASH}  Claude-mac-universal.dmg`))
    }) as typeof fetch)

    expect(requested).toBe(CLAUDE_CHECKSUMS_URL)
  })
})
